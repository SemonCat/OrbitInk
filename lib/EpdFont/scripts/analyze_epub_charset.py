def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    p_scan = sub.add_parser("scan", help="Scan a directory of EPUBs and emit codepoint stats as JSON.")
    p_scan.add_argument("--corpus-dir", required=True, help="Directory to scan recursively for .epub files.")
    p_scan.set_defaults(func=cmd_scan)

    p_build = sub.add_parser("build-manifest", help="Build a charset-file manifest from one or more scans.")
    p_build.add_argument("--scan", nargs="+", required=True, help="One or more scan JSON files.")
    p_build.add_argument("--ui-yaml", nargs="*", default=[], help="UI translation YAML(s) to always include.")
    p_build.add_argument(
        "--coverage-rule", choices=["count1", "count2", "han99_99"], default="count2",
        help="Corpus coverage rule for Han ideographs (default: count2).",
    )
    p_build.add_argument("--max-intervals", type=int, default=700, help="Per-style interval budget (default: 700).")
    p_build.add_argument(
        "--font", required=True,
        help="TTF/OTF to cross-check for missing glyphs and to drive the font-aware interval merge "
             "(requires fontTools). Required: without real font coverage, the merge step cannot tell "
             "which gaps fontconvert_sdcard.py would re-split, so it cannot honestly promise a budget.",
    )
    p_build.add_argument("--output", required=True, help="Output manifest path (for fontconvert_sdcard.py --charset-file).")
    p_build.add_argument("--stats-output", help="Output stats JSON path (default: stdout).")
    p_build.set_defaults(func=cmd_build_manifest)

    return parser


def main(argv: Optional[Sequence[str]] = None) -> None:
    parser = build_parser()
    args = parser.parse_args(argv)
    args.func(args)


