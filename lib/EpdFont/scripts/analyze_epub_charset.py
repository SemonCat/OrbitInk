_YAML_LINE_RE = re.compile(r'^([A-Za-z_][A-Za-z0-9_]*):\s*"(.*)"\s*$')


def load_yaml_string_values(path: str) -> List[str]:
    """Minimal reader for this project's constrained YAML subset (see
    gen_i18n.py) -- extracts every "KEY: "value"" string value, ignoring
    _-prefixed metadata keys. Good enough for codepoint harvesting; does not
    need full YAML semantics.
    """
    values = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            m = _YAML_LINE_RE.match(line.strip())
            if not m:
                continue
            key, value = m.group(1), m.group(2)
            if key.startswith("_"):
                continue
            # Undo the same backslash escapes gen_i18n.py writes: \\ \" \n
            value = (
                value.replace("\\n", "\n").replace('\\"', '"').replace("\\\\", "\\")
            )
            values.append(value)
    return values


def load_scan(paths: Sequence[str]) -> Tuple[Counter, Set[int], int]:
    body_counts: Counter = Counter()
    meta_codepoints: Set[int] = set()
    book_count = 0
    for p in paths:
        with open(p, "r", encoding="utf-8") as f:
            data = json.load(f)
        for cp_str, n in data.get("body_counts", {}).items():
            body_counts[int(cp_str)] += n
        meta_codepoints.update(data.get("meta_codepoints", []))
        book_count += data.get("book_count", 0)
    return body_counts, meta_codepoints, book_count


# Rough "is this a Han-ideograph-ish codepoint" test for the 99.99%
# cumulative-occurrence coverage rule. Deliberately broad (covers the CJK
# Unified block and its common extensions) since the rule is about how much
# of the corpus's *ideograph* mass a cutoff preserves, not a precise
# script-detection routine.
_HAN_RANGES = [
    (0x3400, 0x4DBF),   # Extension A
    (0x4E00, 0x9FFF),   # CJK Unified Ideographs
    (0xF900, 0xFAFF),   # CJK Compatibility Ideographs
    (0x20000, 0x2A6DF), # Extension B
    (0x2A700, 0x2B73F), # Extension C
]


def is_han(cp: int) -> bool:
    return any(lo <= cp <= hi for lo, hi in _HAN_RANGES)


def select_by_rule(body_counts: Counter, rule: str) -> Set[int]:
    """Apply one named corpus coverage rule to body_counts, returning the
    selected codepoint set (non-Han codepoints in body_counts are always
    included regardless of rule -- the count threshold / percentile cutoff
    only trims the long tail of rare Han ideographs; a rarely-used Latin
    letter or punctuation mark is cheap to keep and not the RAM risk).
    """
    non_han = {cp for cp in body_counts if not is_han(cp)}
    han_counts = {cp: n for cp, n in body_counts.items() if is_han(cp)}

    if rule == "count1":
        selected_han = set(han_counts)
    elif rule == "count2":
        selected_han = {cp for cp, n in han_counts.items() if n >= 2}
    elif rule == "han99_99":
        total = sum(han_counts.values())
        if total == 0:
            selected_han = set()
        else:
            threshold = total * 0.9999
            ranked = sorted(han_counts.items(), key=lambda kv: (-kv[1], kv[0]))
            cumulative = 0
            selected_han = set()
            for cp, n in ranked:
                if cumulative >= threshold:
                    break
                selected_han.add(cp)
                cumulative += n
    else:
        raise ValueError(f"unknown coverage rule: {rule}")

    return non_han | selected_han


def report_rule_comparison(body_counts: Counter, always_include: Set[int]) -> Dict[str, Dict]:
    """Compute, for each candidate rule, the selected-set size and the
    NATURAL (pre-budget-merge) interval count once combined with
    always_include -- the number the coverage rule should actually be
    chosen on (interval count, not character count; see module docstring).
    """
    report = {}
    for rule in ("count1", "count2", "han99_99"):
        selected = select_by_rule(body_counts, rule) | always_include
        intervals = merge_adjacent(selected)
        report[rule] = {
            "selected_codepoints": len(selected),
            "natural_intervals": len(intervals),
        }
    return report


def write_manifest(intervals: Sequence[Tuple[int, int]], path: str, header_comment: str) -> None:
    with open(path, "w", encoding="ascii") as f:
        f.write(f"# {header_comment}\n")
        for start, end in intervals:
            f.write(f"0x{start:04X} 0x{end:04X}\n")


def load_font_cmap(font_path: str) -> Set[int]:
    """Return the set of codepoints the given font's best cmap covers.
    Requires fontTools (only used in the local, font-aware phase -- never
    during the remote scan phase).
    """
    from fontTools.ttLib import TTFont

    font = TTFont(font_path, lazy=True)
    cmap = font.getBestCmap() or {}
    font.close()
    return set(cmap.keys())


def check_missing_glyphs(codepoints: Set[int], font_path: str) -> List[int]:
    """Return the sorted list of codepoints in `codepoints` that the given
    font's cmap does not cover."""
    font_cmap = load_font_cmap(font_path)
    return sorted(cp for cp in codepoints if cp not in font_cmap)


def cmd_build_manifest(args: argparse.Namespace) -> None:
    body_counts, meta_codepoints, book_count = load_scan(args.scan)

    always_include: Set[int] = set()
    for lo, hi in ESSENTIAL_INTERVALS:
        always_include.update(range(lo, hi + 1))
    always_include.update(meta_codepoints)

    ui_codepoints: Set[int] = set()
    if args.ui_yaml:
        for yaml_path in args.ui_yaml:
            for value in load_yaml_string_values(yaml_path):
                ui_codepoints.update(ord(ch) for ch in value if not ch.isspace())
    always_include.update(ui_codepoints)

    rule_comparison = report_rule_comparison(body_counts, always_include)

    selected = select_by_rule(body_counts, args.coverage_rule) | always_include

    # Loaded once and reused for both the missing-glyph report and the
    # font-aware merge below -- see merge_with_budget's docstring for why the
    # merge step needs real font coverage, not just Unicode-codepoint gaps:
    # fontconvert_sdcard.py's own rasterizer re-splits any interval wherever
    # the font itself has no glyph for a codepoint inside it, so merging
    # across a gap the font can't fill would be silently undone at generation
    # time and understate the real resident interval count.
    font_cmap = load_font_cmap(args.font)
    missing_glyphs = sorted(cp for cp in selected if cp not in font_cmap)
    missing_ui_glyphs = sorted(set(missing_glyphs) & ui_codepoints)

    final_intervals, extra_glyphs = merge_with_budget(selected, args.max_intervals, font_covered=font_cmap)
    budget_met = len(final_intervals) <= args.max_intervals
    if not budget_met:
        print(
            f"\nWARNING: could not reach the {args.max_intervals}-interval budget -- "
            f"{len(final_intervals)} intervals is the floor achievable without merging across a gap "
            f"the font can't fill (see 'budget_met': false in stats). Consider a coarser manifest, "
            f"a font with denser Han coverage, or accepting the higher figure.",
            file=sys.stderr,
        )

    interval_bytes = len(final_intervals) * 6  # BmpInterval16, see SdCardFont.h

    write_manifest(
        final_intervals,
        args.output,
        header_comment=(
            f"generated by analyze_epub_charset.py build-manifest, rule={args.coverage_rule}, "
            f"max_intervals={args.max_intervals}, books={book_count}"
        ),
    )

    stats = {
        "schema": 1,
        "book_count": book_count,
        "coverage_rule_used": args.coverage_rule,
        "rule_comparison_natural_intervals": rule_comparison,
        "max_intervals_budget": args.max_intervals,
        "budget_met": budget_met,
        "final_interval_count": len(final_intervals),
        "final_selected_codepoints": len(selected),
        "extra_glyphs_from_merging": extra_glyphs,
        "interval_table_bytes_per_loaded_style": interval_bytes,
        "always_include_count": len(always_include),
        "ui_codepoints_count": len(ui_codepoints),
        "meta_title_codepoints_count": len(meta_codepoints),
        "missing_glyphs_in_font": missing_glyphs,
        "missing_ui_required_glyphs": missing_ui_glyphs,
    }
    if args.stats_output:
        with open(args.stats_output, "w", encoding="utf-8") as f:
            json.dump(stats, f, indent=2, ensure_ascii=False)
    else:
        json.dump(stats, sys.stdout, indent=2, ensure_ascii=False)
        sys.stdout.write("\n")

    if missing_ui_glyphs:
        print(
            f"\nCRITICAL: {len(missing_ui_glyphs)} UI-required codepoint(s) have no glyph in "
            f"{args.font}: {[hex(c) for c in missing_ui_glyphs]}",
            file=sys.stderr,
        )
        sys.exit(1)


