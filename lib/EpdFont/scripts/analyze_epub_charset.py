#!/usr/bin/env python3
"""Reproducible EPUB corpus charset analyzer for SD-card font generation.

Two phases, deliberately separated so the heavy corpus scan never needs the
font file (and can run entirely on stdlib, e.g. streamed over SSH to a
read-only host), while the font-aware decision step never needs the book
corpus (only the small stats blob the scan phase produces):

  scan            Walk a directory of .epub files, strip markup from every
                  content document, and count Unicode codepoint occurrences.
                  Also collects codepoints from each book's OPF <dc:title>/
                  <dc:creator> and from the .epub filename and its containing
                  directory name (title/metadata text, not body prose -- see
                  ALWAYS_INCLUDE_CATEGORY_TITLE below). Stdlib only. Prints a
                  single JSON object to stdout; never prints book text itself
                  outside of the aggregated per-codepoint counts.

  build-manifest  Combine one or more scan JSON blobs with: an explicit
                  "always include" source (e.g. a UI translation YAML's
                  string values), an essential ASCII/CJK-punctuation
                  baseline, a corpus coverage rule, and a per-style interval
                  budget. Emits a deterministic interval manifest (for
                  fontconvert_sdcard.py's --charset-file) plus a JSON stats
                  report. Requires fontTools only if --font is given (to
                  cross-check the selected codepoints against a real font's
                  cmap and report missing glyphs) -- otherwise stdlib only.

Manifest file format (consumed by fontconvert_sdcard.py --charset-file):
one interval per line, "START END" as 0x-prefixed hex, inclusive on both
ends. Blank lines and lines starting with '#' are ignored. Example:

    # generated by analyze_epub_charset.py, see stats JSON for provenance
    0x0020 0x007E
    0x4E2D 0x4E2D
    0x6587 0x6587

Usage:
    # Phase 1 (run once per corpus location; safe to run over SSH stdin):
    python3 analyze_epub_charset.py scan --corpus-dir /path/to/epubs > scan.json

    # Phase 2 (local; needs the UI yaml and, for glyph-coverage checking, the font):
    python3 analyze_epub_charset.py build-manifest \\
        --scan scan.json \\
        --ui-yaml lib/I18n/translations/chinese-traditional.yaml \\
        --coverage-rule count2 \\
        --max-intervals 700 \\
        --font GuanKiapTsingKhai.ttf \\
        --output manifest.txt \\
        --stats-output stats.json
"""

from __future__ import annotations

import argparse
import heapq
import html
import json
import os
import re
import sys
import zipfile
from collections import Counter
from typing import Dict, Iterable, List, Optional, Sequence, Set, Tuple

# --- Essential baseline: always included regardless of corpus/UI content ---
# ASCII printable range, CJK Symbols and Punctuation, Halfwidth and Fullwidth
# Forms (covers fullwidth Latin + fullwidth punctuation used in CJK
# typesetting), common curly quotes/dashes/ellipsis, and the replacement
# character. Mirrors the ranges fontconvert_sdcard.py's own "cjk"/"reading"
# presets already use, for consistency with existing conventions.
ESSENTIAL_INTERVALS: List[Tuple[int, int]] = [
    (0x0020, 0x007E),  # ASCII printable
    (0x2018, 0x201D),  # curly single/double quotes
    (0x2013, 0x2014),  # en dash, em dash
    (0x2026, 0x2026),  # horizontal ellipsis
    (0x3000, 0x303F),  # CJK Symbols and Punctuation
    (0xFF00, 0xFFEF),  # Halfwidth and Fullwidth Forms
    (0xFFFD, 0xFFFD),  # replacement character
]

# Content-document extensions considered "body text" inside an epub zip.
_CONTENT_EXTENSIONS = (".xhtml", ".html", ".htm")

_TAG_RE = re.compile(r"<[^>]*>")
_SCRIPT_STYLE_RE = re.compile(r"<(script|style)\b[^>]*>.*?</\1>", re.IGNORECASE | re.DOTALL)

_DC_NS = "{http://purl.org/dc/elements/1.1/}"


# ---------------------------------------------------------------------------
# Phase 1: scan
# ---------------------------------------------------------------------------


def strip_html_regex(markup: str) -> str:
    """Fallback stripper for content that doesn't parse as strict XML.

    Removes <script>/<style> blocks first (their text is not prose), strips
    remaining tags, then decodes HTML/XML entities (named and numeric).
    """
    without_scripts = _SCRIPT_STYLE_RE.sub(" ", markup)
    without_tags = _TAG_RE.sub(" ", without_scripts)
    return html.unescape(without_tags)


def strip_html(markup: str) -> str:
    """Extract plain text from one XHTML/HTML document.

    Tries strict XML parsing first (correct entity handling, exact
    script/style exclusion via the element tree) and falls back to a
    regex-based stripper for malformed documents, which real-world EPUBs
    occasionally contain.
    """
    import xml.etree.ElementTree as ET

    try:
        root = ET.fromstring(markup)
    except ET.ParseError:
        return strip_html_regex(markup)

    parts: List[str] = []

    def walk(el: "ET.Element") -> None:
        tag = el.tag.rsplit("}", 1)[-1].lower() if isinstance(el.tag, str) else ""
        if tag in ("script", "style"):
            return
        if el.text:
            parts.append(el.text)
        for child in el:
            walk(child)
            if child.tail:
                parts.append(child.tail)

    walk(root)
    return "".join(parts)


def find_opf_paths(zf: zipfile.ZipFile) -> List[str]:
    """Resolve the OPF package document path(s) via META-INF/container.xml.

    Falls back to any top-level *.opf file if the container manifest is
    missing or unparsable -- real-world EPUBs are not always spec-perfect.
    """
    import xml.etree.ElementTree as ET

    try:
        container = zf.read("META-INF/container.xml").decode("utf-8", errors="replace")
        root = ET.fromstring(container)
        paths = [
            el.attrib["full-path"]
            for el in root.iter()
            if el.tag.endswith("rootfile") and "full-path" in el.attrib
        ]
        if paths:
            return paths
    except (KeyError, ET.ParseError):
        pass
    return [n for n in zf.namelist() if n.lower().endswith(".opf")]


def extract_opf_title_creator(zf: zipfile.ZipFile) -> str:
    """Return concatenated dc:title / dc:creator text from the OPF, or ''."""
    import xml.etree.ElementTree as ET

    texts: List[str] = []
    for opf_path in find_opf_paths(zf):
        try:
            data = zf.read(opf_path).decode("utf-8", errors="replace")
            root = ET.fromstring(data)
        except (KeyError, ET.ParseError):
            continue
        for el in root.iter():
            tag = el.tag
            if tag in (f"{_DC_NS}title", f"{_DC_NS}creator") and el.text:
                texts.append(el.text)
    return " ".join(texts)


def scan_one_epub(path: str) -> Tuple[Counter, str]:
    """Return (body_text_codepoint_counter, title_metadata_text) for one epub.

    title_metadata_text combines OPF dc:title/dc:creator with the filename
    (without extension) and containing directory name -- all treated as
    "always include" text by the caller, never subject to the corpus
    coverage-count threshold, since a title/filename character appearing
    even once must not turn into a tofu box in the library or file browser.
    """
    body_counts: Counter = Counter()
    meta_text_parts: List[str] = []

    with zipfile.ZipFile(path) as zf:
        meta_text_parts.append(extract_opf_title_creator(zf))
        for name in zf.namelist():
            if name.lower().endswith(_CONTENT_EXTENSIONS):
                try:
                    raw = zf.read(name).decode("utf-8", errors="replace")
                except (KeyError, zipfile.BadZipFile):
                    continue
                text = strip_html(raw)
                body_counts.update(ord(ch) for ch in text if not ch.isspace())

    base = os.path.splitext(os.path.basename(path))[0]
    parent_dir = os.path.basename(os.path.dirname(os.path.abspath(path)))
    meta_text_parts.append(base)
    meta_text_parts.append(parent_dir)

    return body_counts, " ".join(meta_text_parts)


def scan_corpus(corpus_dir: str) -> Dict:
    """Scan every .epub under corpus_dir (recursive). Returns the scan JSON dict."""
    body_counts: Counter = Counter()
    meta_codepoints: Set[int] = set()
    book_count = 0
    errors: List[Dict[str, str]] = []

    for dirpath, _dirnames, filenames in os.walk(corpus_dir):
        for fname in filenames:
            if not fname.lower().endswith(".epub"):
                continue
            full_path = os.path.join(dirpath, fname)
            try:
                counts, meta_text = scan_one_epub(full_path)
            except Exception as exc:  # noqa: BLE001 - a single bad book must not abort the scan
                errors.append({"file": full_path, "error": f"{type(exc).__name__}: {exc}"})
                continue
            book_count += 1
            body_counts.update(counts)
            meta_codepoints.update(ord(ch) for ch in meta_text if not ch.isspace())

    return {
        "schema": 1,
        "book_count": book_count,
        "body_counts": {str(cp): n for cp, n in sorted(body_counts.items())},
        "meta_codepoints": sorted(meta_codepoints),
        "errors": errors,
    }


def cmd_scan(args: argparse.Namespace) -> None:
    result = scan_corpus(args.corpus_dir)
    json.dump(result, sys.stdout, ensure_ascii=True)
    sys.stdout.write("\n")
    if result["errors"]:
        for err in result["errors"]:
            print(f"WARNING: {err['file']}: {err['error']}", file=sys.stderr)
    print(
        f"Scanned {result['book_count']} book(s), "
        f"{len(result['body_counts'])} distinct body codepoints, "
        f"{len(result['meta_codepoints'])} distinct title/metadata codepoints "
        f"({len(result['errors'])} error(s))",
        file=sys.stderr,
    )


# ---------------------------------------------------------------------------
# Interval merging
# ---------------------------------------------------------------------------


def merge_adjacent(codepoints: Iterable[int]) -> List[Tuple[int, int]]:
    """Merge a codepoint set into the minimal set of contiguous intervals."""
    pts = sorted(set(codepoints))
    if not pts:
        return []
    intervals: List[List[int]] = []
    start = prev = pts[0]
    for p in pts[1:]:
        if p == prev + 1:
            prev = p
        else:
            intervals.append([start, prev])
            start = prev = p
    intervals.append([start, prev])
    return [(a, b) for a, b in intervals]


def _font_covers_range(sorted_font_cps: Sequence[int], start: int, end: int) -> bool:
    """True if every codepoint in [start, end] is in the sorted font coverage
    array (bisect-based -- O(log n), never iterates the range itself, which
    matters since candidate gaps can span thousands of codepoints)."""
    import bisect

    lo = bisect.bisect_left(sorted_font_cps, start)
    hi = bisect.bisect_right(sorted_font_cps, end)
    return (hi - lo) == (end - start + 1)


def merge_with_budget(
    codepoints: Iterable[int],
    max_intervals: int,
    font_covered: Optional[Set[int]] = None,
) -> Tuple[List[Tuple[int, int]], int]:
    """Merge codepoints into at most max_intervals contiguous intervals.

    Deterministic greedy strategy: repeatedly merge the two adjacent
    (already-selected) intervals separated by the smallest gap, until the
    count is at or below the budget. Each merge "fills in" the unselected
    codepoints between the two intervals -- those become extra rasterized
    glyphs that were not required by any coverage rule, purely a RAM/flash
    tradeoff to keep the resident interval table small. Ties broken by the
    lower interval's position (stable via heap tuple comparison).

    font_covered, when given, restricts which gaps are eligible to merge: a
    gap is only mergeable if the font has a glyph for EVERY codepoint inside
    it. This matters because fontconvert_sdcard.py's own rasterizer silently
    re-splits an interval wherever the font has no glyph for a codepoint
    inside it (see rasterize_font_style's "Validate intervals against font"
    step) -- merging across a gap the font can't actually fill would be
    undone at generation time, silently inflating the real interval count
    past what this function promised. Without font_covered, every gap is
    assumed mergeable (the pre-font-aware behavior) -- only correct if the
    caller separately guarantees the font covers the merged spans.

    If every eligible (fully font-covered) gap has been merged and the count
    is still above max_intervals, that is the true floor achievable without
    dropping a required codepoint: returns early with a smaller reduction
    than requested rather than lying about the final count. Callers must
    check len(result) against their budget rather than assume it was met.

    Returns (final_intervals, extra_glyphs_added).
    """
    intervals = [list(iv) for iv in merge_adjacent(codepoints)]
    n = len(intervals)
    if n <= max_intervals or n == 0:
        return [(a, b) for a, b in intervals], 0

    sorted_font_cps = sorted(font_covered) if font_covered is not None else None

    nxt = list(range(1, n)) + [-1]
    alive = [True] * n

    def gap(i: int) -> int:
        j = nxt[i]
        return intervals[j][0] - intervals[i][1] - 1

    def eligible(i: int) -> bool:
        if sorted_font_cps is None:
            return True
        j = nxt[i]
        g = gap(i)
        if g == 0:
            return True  # truly adjacent, nothing to pave
        return _font_covers_range(sorted_font_cps, intervals[i][1] + 1, intervals[j][0] - 1)

    heap: List[Tuple[int, int]] = []
    for i in range(n - 1):
        if eligible(i):
            heapq.heappush(heap, (gap(i), i))

    count = n
    extra_glyphs = 0
    while count > max_intervals and heap:
        g, i = heapq.heappop(heap)
        if not alive[i] or nxt[i] == -1 or not alive[nxt[i]]:
            continue
        if gap(i) != g:
            if eligible(i):
                heapq.heappush(heap, (gap(i), i))
            continue
        if not eligible(i):
            continue
        j = nxt[i]
        intervals[i][1] = intervals[j][1]
        extra_glyphs += g
        alive[j] = False
        nxt[i] = nxt[j]
        if nxt[i] != -1 and eligible(i):
            heapq.heappush(heap, (gap(i), i))
        count -= 1

    return [(intervals[i][0], intervals[i][1]) for i in range(n) if alive[i]], extra_glyphs


